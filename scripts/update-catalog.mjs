import { createHash } from "node:crypto";
import prettier from "prettier";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const packageJson = JSON.parse(
  await readFile(join(root, "package.json"), "utf8"),
);
const version = packageJson.version;
if (version !== "0.2.0")
  throw new Error(
    `Update the versioned asset directory before catalog generation: ${version}`,
  );
const basePath = `/kice-assets/${version}`;
const mediaTypes = {
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json",
  ".md": "text/markdown; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".ts": "text/plain; charset=utf-8",
};

async function files(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    result.push(...(entry.isDirectory() ? await files(path) : [path]));
  }
  return result.sort();
}

const assetFiles = await files(join(root, "assets"));
const stemCounts = new Map();
for (const file of assetFiles) {
  const stem = relative(join(root, "assets"), file)
    .split(sep)
    .join("/")
    .replace(extname(file), "");
  stemCounts.set(stem, (stemCounts.get(stem) ?? 0) + 1);
}
const assets = {};
for (const file of assetFiles) {
  const path = relative(join(root, "assets"), file).split(sep).join("/");
  const mediaType = mediaTypes[extname(file)];
  if (!mediaType) throw new Error(`No media type registered for ${path}`);
  const bytes = await readFile(file);
  const stem = path.slice(0, -extname(path).length);
  const id = stemCounts.get(stem) > 1 ? path : stem;
  assets[id] = {
    path,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    bytes: bytes.length,
    mediaType,
  };
}

const catalog = { version, basePath, assets };
const json = await prettier.format(`${JSON.stringify(catalog, null, 2)}\n`, {
  filepath: join(root, "catalog.json"),
});
await writeFile(join(root, "catalog.json"), json);
const source = `// Generated by scripts/update-catalog.mjs; edit the packaged files, then regenerate.\nexport const ASSET_VERSION = ${JSON.stringify(version)};\nexport const ASSET_BASE_PATH = ${JSON.stringify(basePath)};\nexport const ASSETS = ${JSON.stringify(assets, null, 2)} as const;\nexport type AssetId = keyof typeof ASSETS;\n`;
await writeFile(
  join(root, "src/catalog.ts"),
  await prettier.format(source, { filepath: join(root, "src/catalog.ts") }),
);
console.log(`Indexed ${Object.keys(assets).length} files under ${basePath}.`);
